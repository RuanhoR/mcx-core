/** 游戏绘制点阵字形时的透明度阈值（双线性插值之后；真机 1.20.1：「。」与「，」逐像素吻合） */
export const GAME_GLYPH_THRESHOLD = 0.35

/** 覆盖字形的墨迹宽（半像素）：字距 = 墨迹宽 / 2 + 1（与 Unifont 同一规则） */
export function gameGlyphInk(cp: number): number | undefined {
    const hex = GAME_GLYPHS[cp]
    if (!hex) return undefined
    let lo = 16, hi = -1
    for (let r = 0; r < 16; r++) {
        const row = parseInt(hex.slice(r * 4, r * 4 + 4), 16)
        for (let x = 0; x < 16; x++) if ((row >> (15 - x)) & 1) { lo = Math.min(lo, x); hi = Math.max(hi, x) }
    }
    return hi < 0 ? 0 : hi - lo + 1
}
